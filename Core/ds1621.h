/**
 * @file ds1621.h
 * @brief Заголовочный файл драйвера для цифрового термометра DS1621.
 *
 * Содержит определения типов данных, конфигурационные константы
 * и прототипы функций для взаимодействия с микросхемой DS1621.
 */

#ifndef DS1621_H_
#define DS1621_H_

#include "misc.h"

// ===== Конфигурация пользователя =====
#include "stm32l011_my_hal.h"
/// @brief I2C интерфейс, к которому подключен DS1621.
#define DS1621_I2C 						I2C1
/// @brief 7-битный I2C адрес устройства, сдвинутый влево на 1 (LSB = 0).
/// Адрес 0x4F по умолчанию (пины A2, A1, A0 подключены к GND).
#define DS1621_I2C_ADDR					(0x4F<<1)
// ===== Конец конфигурации =====

/**
 * @brief Структура для представления температуры.
 *
 * Содержит целую часть температуры и бит 0.5 градуса Цельсия.
 */
typedef struct
{
	int8_t  temp;      ///< Целая часть температуры (в градусах Цельсия).
	uint8_t temp_05;   ///< Флаг для дробной части: 1 - добавить 0.5°C к целой части.
	                   ///< Пример: temp = -3, temp_05 = 1 -> температура -2.5°C.
}ds1621_temp_t;

/**
 * @brief Структура для представления регистра конфигурации DS1621.
 *
 * Биты регистра конфигурации (0xAC):
 * - D7: Not Used
 * - D6: Not Used
 * - D5: 1 - результат конвертации готов (устанавливается автоматически)
 * - D4: 1 - температура превысила THIGH (THF)
 * - D3: 1 - температура ниже TLOW (TLF)
 * - D2: 1 - EEPROM занят (NVB)
 * - D1: 0 - активный уровень алерта низкий, 1 - высокий (POL)
 * - D0: 0 - непрерывный режим, 1 - однократное измерение (1-Shot)
 */
typedef struct
{
	uint8_t _1shot   :1; ///< Режим: 0 - непрерывный, 1 - однократное измерение (One-Shot).
	uint8_t pol      :1; ///< Полярность алерта: 0 - активный низкий, 1 - активный высокий.
	uint8_t reserved :2; ///< Зарезервировано (должно быть 0).
	uint8_t nvb      :1; ///< Флаг занятости EEPROM (NVB).
	uint8_t tlf      :1; ///< Флаг низкой температуры (TLF). Устанавливается, если T < TLOW.
	uint8_t thf      :1; ///< Флаг высокой температуры (THF). Устанавливается, если T > THIGH.
	uint8_t done     :1; ///< Флаг завершения конвертации (DONE). Устанавливается по окончании измерения.
}ds1621_cfg_t;

/**
 * @brief Чтение регистра конфигурации DS1621.
 * @param[out] cfg Указатель на переменную для сохранения значения конфигурации.
 * @return Результат операции I2C.
 */
int DS1621_get_cfg(ds1621_cfg_t* cfg);

/**
 * @brief Запись в регистр конфигурации DS1621.
 * @param[in] cfg Указатель на переменную с новым значением конфигурации.
 * @note После вызова функции требуется ожидание 10 мс для завершения записи в EEPROM.
 * @return Результат операции I2C.
 */
int DS1621_set_cfg(ds1621_cfg_t* cfg);

/**
 * @brief Чтение текущего значения температуры из DS1621.
 * @return Структура ds1621_temp_t с прочитанным значением температуры.
 *         В случае ошибки чтения, возвращается температура -99.0°C.
 */
ds1621_temp_t DS1621_get_temp();

/**
 * @brief Установка порогов температуры THIGH и TLOW.
 * @param[in] hi Порог THIGH (температура выше - срабатывает THF).
 * @param[in] low Порог TLOW (температура ниже - срабатывает TLF).
 * @note После вызова функции требуется ожидание 10 мс для завершения записи в EEPROM.
 * @return Результат последней операции I2C.
 */
int DS1621_set_thresholds(ds1621_temp_t hi, ds1621_temp_t low);

/**
 * @brief Чтение порогов температуры THIGH и TLOW.
 * @param[out] hi Указатель на переменную для сохранения порога THIGH.
 * @param[out] low Указатель на переменную для сохранения порога TLOW.
 * @return Результат последней операции I2C.
 */
int DS1621_get_thresholds(ds1621_temp_t *hi, ds1621_temp_t *low);

/**
 * @brief Запуск измерения температуры (команда 0xEE).
 * @note Используется в режиме One-Shot. В непрерывном режиме измерение идёт автоматически.
 * @return Результат операции I2C.
 */
int DS1621_start_convert();

/**
 * @brief Остановка измерения температуры (команда 0x22).
 * @note Используется для остановки непрерывного режима.
 * @return Результат операции I2C.
 */
int DS1621_stop_convert();

#endif /* DS1621_H_ */