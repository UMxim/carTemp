/**
 * @file ds1621.c
 * @brief Драйвер для цифрового термометра DS1621 через I2C.
 *
 * Данный драйвер предоставляет функции для взаимодействия с микросхемой DS1621,
 * включая чтение температуры, установку порогов, управление конвертацией
 * и настройку режимов работы.
 *
 * Логика работы:
 * 1. Инициализация: DS1621 обычно настраивается на однократное измерение
 *    (режим One-Shot) или непрерывное измерение. Если используется One-Shot,
 *    перед каждым чтением температуры нужно запускать конвертацию командой
 *    DS1621_start_convert(). Если используется непрерывный режим, измерение
 *    происходит автоматически.
 * 2. Запуск конвертации: Для режима One-Shot вызывается DS1621_start_convert().
 *    DS1621 начнёт измерение температуры.
 * 3. Ожидание завершения: В режиме One-Shot может потребоваться ожидание
 *    завершения измерения (обычно занимает до 750 мс для 12-битного разрешения).
 *    Это можно проверить, например, через флаг D5 в регистре конфигурации.
 * 4. Чтение температуры: Вызывается DS1621_get_temp(). Функция читает 16-битное
 *    значение температуры из регистра 0xAA. Формат: старший байт - целая часть,
 *    младший байт - дробная (бит 0 - 0.5 градуса).
 * 5. Управление порогами: Пороги для алертов (THIGH/LOW) устанавливаются
 *    через DS1621_set_thresholds() и читаются через DS1621_get_thresholds().
 * 6. Остановка конвертации: В режиме непрерывного измерения можно остановить
 *    измерение командой DS1621_stop_convert().
 * 7. Настройка: Регистр конфигурации (0xAC) позволяет управлять режимами,
 *    включать/выключать алерт-вывод и т.д. через DS1621_set_cfg / DS1621_get_cfg.
 *
 * @note Предполагается, что функции i2c_read и i2c_write реализованы отдельно
 *       и корректно обрабатывают адресацию I2C.
 */

#include "ds1621.h"

// --- Определения команд и регистров ---
#define DS1621_CFG		0xAC ///< Адрес регистра конфигурации
#define DS1621_START	0xEE ///< Команда запуска конвертации температуры
#define DS1621_STOP		0x22 ///< Команда остановки конвертации температуры
#define DS1621_READ		0xAA ///< Адрес регистра чтения температуры
#define DS1621_TH		0xA1 ///< Адрес регистра порога THIGH
#define DS1621_TL		0xA2 ///< Адрес регистра порога TLOW


/**
 * @brief Внутренняя функция для записи данных в регистр DS1621 по I2C.
 *
 * @param[in] reg Адрес регистра для записи.
 * @param[in] buff Указатель на буфер с данными для записи.
 * @param[in] size Количество байт для записи из буфера.
 * @return Результат операции I2C (обычно количество переданных байт или код ошибки).
 */
static int ds1621_i2c_write(uint8_t reg, uint8_t *buff, uint16_t size)
{
	return i2c_write(DS1621_I2C, DS1621_I2C_ADDR, &reg, 1, buff, size);
}

/**
 * @brief Внутренняя функция для чтения данных из регистра DS1621 по I2C.
 *
 * @param[in] reg Адрес регистра для чтения.
 * @param[out] buff Указатель на буфер для получения данных.
 * @param[in] size Количество байт для чтения в буфер.
 * @return Результат операции I2C (обычно количество полученных байт или код ошибки).
 */
static int ds1621_i2c_read(uint8_t reg, uint8_t *buff, uint16_t size)
{
	return i2c_read(DS1621_I2C, DS1621_I2C_ADDR, &reg, sizeof(reg), buff, size);
}


/**
 * @brief Чтение регистра конфигурации DS1621.
 *
 * Читает содержимое 8-битного регистра конфигурации (0xAC).
 *
 * @param[out] cfg Указатель на переменную типа ds1621_cfg_t для сохранения значения.
 * @return Результат операции I2C.
 */
int DS1621_get_cfg(ds1621_cfg_t* cfg)
{
	return ds1621_i2c_read(DS1621_CFG, (uint8_t*)cfg, sizeof(ds1621_cfg_t));
}

/**
 * @brief Запись в регистр конфигурации DS1621.
 *
 * Устанавливает содержимое 8-битного регистра конфигурации (0xAC).
 * Важно: биты D7 и D6 (режимы) могут быть проигнорированы при записи.
 *
 * @param[in] cfg Указатель на переменную типа ds1621_cfg_t с новым значением.
 * @return Результат операции I2C.
 */
int DS1621_set_cfg(ds1621_cfg_t* cfg)
{
	return ds1621_i2c_write(DS1621_CFG, (uint8_t*)cfg, sizeof(ds1621_cfg_t));
}


/**
 * @brief Чтение текущего значения температуры из DS1621.
 *
 * Читает 16-битное значение температуры из регистра 0xAA.
 * Формат: старший байт - целая часть (в знаковом формате),
 *         младший байт - дробная часть (бит 0 - 0.5 градуса).
 *
 * @return Структура ds1621_temp_t с прочитанным значением.
 *         Если чтение не удалось, возвращается температура -99.0°C.
 */
ds1621_temp_t DS1621_get_temp()
{
	ds1621_temp_t temp;
	int res = ds1621_i2c_read(DS1621_READ, (uint8_t*)&temp, sizeof(ds1621_temp_t));
	if (res <= 0) temp.temp = -99; // Ошибка или неудачное чтение
	return temp;
}

/**
 * @brief Установка порогов температуры THIGH и TLOW.
 *
 * Устанавливает значения порогов для алертов.
 * Перед записью корректирует бит 0.5°C (temp_05) для обоих значений.
 *
 * @param[in] hi Значение порога THIGH (температура выше - алерт).
 * @param[in] low Значение порога TLOW (температура ниже - алерт).
 * @return Результат последней операции I2C (обычно <= 0 означает ошибку).
 */
int DS1621_set_thresholds(ds1621_temp_t hi, ds1621_temp_t low)
{
	int res;
	// Коррекция бита 0.5°C перед записью
	low.temp_05 = low.temp_05 ? 0x80 : 0;
	hi.temp_05 = hi.temp_05 ? 0x80 : 0;

	// Запись THIGH
	res = ds1621_i2c_write(DS1621_TH, (uint8_t*)&hi, sizeof(ds1621_temp_t));
	if (res <= 0 ) return res;
	// Задержка между записями, как рекомендовано в даташите
	Timer_delay_ms(10);
	// Запись TLOW
	res = ds1621_i2c_write(DS1621_TL, (uint8_t*)&low, sizeof(ds1621_temp_t));
	return res;
}

/**
 * @brief Чтение порогов температуры THIGH и TLOW.
 *
 * Читает значения порогов из регистров 0xA1 и 0xA2.
 *
 * @param[out] hi Указатель на переменную для сохранения порога THIGH.
 * @param[out] low Указатель на переменную для сохранения порога TLOW.
 * @return Результат последней операции I2C.
 */
int DS1621_get_thresholds(ds1621_temp_t *hi, ds1621_temp_t *low)
{
	int res;
	// Чтение THIGH
	res = ds1621_i2c_read(DS1621_TH, (uint8_t*)hi, sizeof(ds1621_temp_t));
	if (res <= 0 ) return res;
	// Чтение TLOW
	res = ds1621_i2c_read(DS1621_TL, (uint8_t*)low, sizeof(ds1621_temp_t));
	return res;
}

/**
 * @brief Запуск измерения температуры.
 *
 * Отправляет команду 0xEE для запуска конвертации.
 * Используется для режима One-Shot.
 *
 * @return Результат операции I2C.
 */
int DS1621_start_convert()
{
	return ds1621_i2c_write(DS1621_START, NULL, 0); // Команда без данных
}

/**
 * @brief Остановка измерения температуры.
 *
 * Отправляет команду 0x22 для остановки конвертации.
 * Используется для остановки непрерывного режима.
 *
 * @return Результат операции I2C.
 */
int DS1621_stop_convert()
{
	return ds1621_i2c_write(DS1621_STOP, NULL, 0); // Команда без данных
}