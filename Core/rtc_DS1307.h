/**
 * @file rtc_ds1307.h
 * @brief Заголовочный файл драйвера для RTC DS1307.
 *
 * Этот файл содержит определения типов данных, конфигурационные константы
 * и встроенные функции (static inline) для взаимодействия с микросхемой
 * реального времени DS1307 по шине I2C.
 * Предполагается, что пользователь предоставит реализацию функций i2c_write
 * и i2c_read через подключаемый файл i2c.h.
 *
 * Логика работы:
 * 1. Конфигурация: Пользователь указывает I2C периферию (I2C1) и функции
 *    для чтения/записи через макросы DS1307_I2C_WRITE/READ.
 * 2. Структура данных: Структура DS1307_t представляет собой "зеркало"
 *    регистров DS1307, где каждый бит или группа битов соответствует
 *    определённому полю в регистрах (секунды, минуты, дата и т.д.).
 *    ВНИМАНИЕ: Порядок битов зависит от компилятора и может не совпадать
 *    с порядком в регистрах DS1307. Использование структуры напрямую
 *    для I2C операций требует проверки упаковки и порядка битов.
 * 3. Чтение/Запись: Функции DS1307_Read и DS1307_Write читают или записывают
 *    всю структуру DS1307_t (все регистры времени и конфигурации) за одну
 *    I2C транзакцию, начиная с регистра 0x00 (секунды).
 * 4. Побайтовая запись: Функция DS1307_Write_byte позволяет записать
 *    отдельный байт в указанный регистр DS1307.
 *
 * @note Порядок битов в структуре DS1307_t критичен и должен соответствовать
 *       спецификации DS1307 и порядку байтов, используемому компилятором.
 * @note Макрос DS1307_I2C_READ использует переменную 'reg', объявленную
 *       внутри функции DS1307_Read, что делает его зависимым от контекста.
 */

#ifndef __RTC_DS1307_H__
#define __RTC_DS1307_H__

#include <stddef.h>

// ===== Конфигурация пользователя =====
#include "i2c.h"
/**
 * @brief Макрос для записи данных в DS1307 по I2C.
 * @param reg Адрес регистра для записи.
 * @param data Указатель на буфер с данными.
 * @param size Размер данных для записи.
 * @return Результат операции I2C.
 */
#define DS1307_I2C_WRITE(reg, data, size) i2c_write(I2C1, DS1307_ADDR, &reg, 1, data, size)

/**
 * @brief Макрос для чтения данных из DS1307 по I2C.
 * @param data Указатель на буфер для данных.
 * @param size Размер данных для чтения.
 * @return Результат операции I2C.
 * @note Использует переменную 'reg', объявленную в месте вызова макроса.
 */
#define DS1307_I2C_READ(data, size)       i2c_read (I2C1, DS1307_ADDR, &reg, 1, data, size)

// ===== ДРАЙВЕР =====

/**
 * @brief Структура, представляющая регистры DS1307.
 *
 * Соответствует layout регистров DS1307, как описано в даташите.
 * Представление в виде битовых полей (bit fields).
 * @warning Порядок битов *внутри* одного байта зависит от компилятора
 *          и архитектуры. Использование этой структуры напрямую для
 *          I2C чтения/записи требует проверки соответствия с даташитом.
 */
typedef struct
{
	// Регистр 0x00: секунды
	uint8_t seconds				:4;	///< Младшая цифра секунд (0-9)
	uint8_t seconds_10			:3; ///< Старшая цифра секунд (0-7, для значений 0-9)
	uint8_t ch					:1; ///< Флаг остановки часов (CH): 1 - часы остановлены

	// Регистр 0x01: минуты
	uint8_t minutes				:4; ///< Младшая цифра минут (0-9)
	uint8_t minutes_10			:3; ///< Старшая цифра минут (0-7, для значений 0-9)
	uint8_t minutes_rfu			:1; ///< Зарезервировано (должно быть 0)

	// Регистр 0x02: часы
	uint8_t hours				:4; ///< Младшая цифра часов (0-9, или 0-3 для 24ч формата)
	uint8_t hours_10			:2; ///< Старшая цифра часов (0-3, для 24ч формата: 00-23)
	uint8_t hours_12			:1; ///< Режим 12/24: 0 - 24-часовой, 1 - 12-часовой
	uint8_t hours_rfu			:1; ///< Зарезервировано (должно быть 0)

	// Регистр 0x03: день недели
	uint8_t day					:3; ///< День недели (1-7, 1 - воскресенье)
	uint8_t day_rfu				:5; ///< Зарезервировано (должно быть 0)

	// Регистр 0x04: дата
	uint8_t date				:4; ///< Младшая цифра даты (0-9)
	uint8_t date_10				:2; ///< Старшая цифра даты (0-3, для значений 0-3)
	uint8_t date_rfu			:2; ///< Зарезервировано (должно быть 0)

	// Регистр 0x05: месяц
	uint8_t month				:4; ///< Младшая цифра месяца (0-9)
	uint8_t month_10			:1; ///< Старшая цифра месяца (0-1, для значений 0-1)
	uint8_t month_rfu			:3; ///< Зарезервировано (должно быть 0)

	// Регистр 0x06: год
	uint8_t year				:4; ///< Младшая цифра года (0-9)
	uint8_t year_10				:4; ///< Старшая цифра года (0-9, для значений 00-99)

	// Регистр 0x07: регистр конфигурации (режим SQW/OUT)
	uint8_t cfg_rs				:2;	///< Частота SQW: 00->1Hz, 01->4096Hz, 10->8192Hz, 11->32768Hz
	uint8_t cfg_rfu_0			:2; ///< Зарезервировано (должно быть 0)
	uint8_t cfg_sqwe			:1; ///< Включить SQW: 0 - отключено (OUT), 1 - включено (генератор)
	uint8_t cfg_rfu_1			:2; ///< Зарезервировано (должно быть 0)
	uint8_t cfg_out				:1; ///< Уровень OUT (если SQWE=0): 0 - низкий, 1 - высокий
}DS1307_t;

/// @brief 7-битный I2C адрес DS1307, сдвинутый влево (LSB = 0).
#define DS1307_ADDR (0x68<<1)

/**
 * @brief Читает все регистры времени и конфигурации DS1307.
 *
 * Читает 7 байт (секунды, минуты, часы, день, дата, месяц, год) из DS1307
 * и сохраняет их в структуре DS1307_t. Начинает чтение с регистра 0x00.
 *
 * @param[out] time Указатель на структуру DS1307_t для сохранения данных.
 * @return Результат операции I2C.
 */
static inline int DS1307_Read(DS1307_t *time)
{
	uint8_t reg = 0; // Адрес регистра для чтения (секунды)
	return DS1307_I2C_READ((uint8_t*)time, sizeof(DS1307_t));
}

/**
 * @brief Записывает все регистры времени и конфигурации DS1307.
 *
 * Записывает 7 байт (секунды, минуты, часы, день, дата, месяц, год) в DS1307
 * из структуры DS1307_t. Начинает запись с регистра 0x00.
 *
 * @param[in] time Указатель на структуру DS1307_t с новыми данными.
 * @return Результат операции I2C.
 */
static inline int DS1307_Write(DS1307_t *time)
{
	uint8_t reg = 0; // Адрес регистра для записи (секунды)
	return DS1307_I2C_WRITE(reg, (uint8_t *)time, sizeof(DS1307_t));
}

/**
 * @brief Записывает один байт в указанный регистр DS1307.
 *
 * @param[in] reg Адрес регистра для записи (0x00 - 0x3F).
 * @param[in] byte Значение для записи.
 * @return Результат операции I2C.
 */
static inline int DS1307_Write_byte(uint8_t reg, uint8_t byte)
{
	return DS1307_I2C_WRITE(reg, &byte, 1);
}

#endif //__RTC_DS1307_H__