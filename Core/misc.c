/**
 * @file misc.c
 * @brief Реализация вспомогательных функций из misc.h.
 *
 * Содержит реализацию функций для поиска медианы,
 * преобразования чисел в строки и таймерные функции.
 *
 * Логика работы:
 * - _Sort: Сортирует массив методом вставки.
 * - GetMedian_16: Вызывает _Sort и возвращает средний элемент.
 * - Int_to_str: Преобразует число в строку, разбирая цифры,
 *   корректно обрабатывая отрицательные числа и -2^31.
 * - Timer_set: Инициализирует таймер.
 * - Timer_isExpired: Проверяет истечение, обновляет отметку времени.
 * - Timer_delay_ms: Блокирует выполнение на заданное время.
 */

#include <stdio.h>
#include "misc.h"
#include "stm32l011_my_hal.h"

/**
 * @brief Внутренняя функция сортировки массива методом вставки.
 *
 * Сортирует массив 16-битных значений `arr` размером `n` по возрастанию.
 * Используется в функции GetMedian_16.
 *
 * @param[in,out] arr Указатель на массив для сортировки.
 * @param n Размер массива.
 */
static void _Sort(uint16_t *arr, int n)
{
	for (int i = 1; i < n; i++) {
		uint16_t key = arr[i];
        int j = i - 1;
        while (j >= 0 && arr[j] > key) {
            arr[j + 1] = arr[j];
            j--;
        }
        arr[j + 1] = key;
    }
}

// ====== Интерфейс (interface) ======

/**
 * @brief Поиск медианы в массиве 16-битных значений.
 *
 * Сортирует переданный массив методом вставки и возвращает значение
 * элемента, находящегося в середине отсортированного массива.
 * @warning Массив `arr` изменяется в процессе сортировки.
 *
 * @param[in,out] arr Указатель на массив 16-битных значений. Будет отсортирован.
 * @param n Размер массива. Должен быть больше 0.
 * @return Медианное значение (значение элемента с индексом n/2).
 */
uint16_t GetMedian_16(uint16_t *arr, int n)
{
	_Sort(arr, n);
	// n >> 1 эквивалентно n / 2
	return arr[n>>1];
}

/**
 * @brief Преобразование 32-битного целого числа в строку.
 *
 * Преобразует целое число `var` в строку символов, сохраняя её в буфер `str`.
 * Строка выравнивается вправо (незаполненные позиции слева заполняются пробелами).
 * Символ завершающего нуля ('\0') не добавляется автоматически.
 *
 * @param var Целое число для преобразования.
 * @param[out] str Буфер размером 12 байт для результата.
 * @return Количество значимых символов в числе (без ведущих пробелов).
 */
int32_t Int_to_str(int32_t var, char str[12]) 
{  
	// Временный буфер для сборки строки. Индекс 0 зарезервирован.
    char temp[12] = {0,' ',' ',' ',' ',' ',' ',' ',' ',' ',' ',' '};
    int i = 1; // Индекс для записи в temp
    
    if (var == 0) // Обработка нуля отдельно
	{
        temp[i++] = '0';
    } 
	else 
	{        
        int negative = (var < 0); // Флаг отрицательного числа
        // Обработка специального случая INT32_MIN (-2147483648)
        uint32_t num = (var == -2147483648) ? 2147483648U : (negative ? -var : var);
        
        while (num > 0) // Заполняем temp цифрами в обратном порядке
		{
            temp[i++] = '0' + (num % 10); // Добавляем цифру как символ
            num /= 10; // Переходим к следующей цифре
        }
        
        if (negative) // Добавляем минус, если число отрицательное
		{
            temp[i++] = '-';
        }        
    }

    // Переворачиваем строку из temp в str с выравниванием вправо
    // Последний символ в str получает первый значимый символ из temp и т.д.
    for (int j = 0; j < 12; j++) 
        str[j] = temp[12-j-1];    
    
    return i; // Возвращаем количество значимых символов (включая '-', но не пробелы)
}

// ===== Таймеры (timers) =====

/**
 * @brief Установка программного таймера.
 *
 * Инициализирует таймер, устанавливая его период и отметку времени
 * на текущее значение глобальной переменной `timer_ms`.
 *
 * @param[out] tim Указатель на структуру таймера.
 * @param period Период таймера в миллисекундах.
 */
void Timer_set(timer_t *tim, uint32_t period)
{
	tim->timeStamp = timer_ms;
	tim->period = period;
}

/**
 * @brief Проверка истечения программного таймера.
 *
 * Проверяет, истёк ли период с момента последней установки/срабатывания таймера.
 * Использует арифметику беззнаковых чисел для корректной работы при переполнении
 * `timer_ms`. Если таймер истёк, автоматически обновляет `timeStamp` на `period`
 * вперёд и возвращает 1.
 *
 * @param[in,out] tim Указатель на структуру таймера.
 * @return 1, если таймер истёк, 0 - если нет.
 */
uint8_t Timer_isExpired(timer_t *tim)
{
	// Если период равен 0, таймер считается остановленным
	if (tim->period == 0) return 0;
	// Проверка истечения: разница между текущим временем и отметкой
	// должна быть больше или равна периоду.
	// Используется uint32_t, что позволяет корректно обработать
	// переполнение timer_ms.
	if (timer_ms - tim->timeStamp >= tim->period)
	{
		// Обновление отметки времени на один период вперёд
		// (предотвращает "проскакивание" интервалов при медленном опросе)
		tim->timeStamp += tim->period;
		return 1;
	}
	return 0;
}

/**
 * @brief Блокирующая задержка в миллисекундах.
 *
 * Создаёт локальный программный таймер и ждёт, пока он не истечёт,
 * тем самым приостанавливая выполнение текущего потока/кода на
 * заданное количество миллисекунд.
 * Использует `Timer_set` и `Timer_isExpired`.
 *
 * @param ms Количество миллисекунд для задержки.
 */
void Timer_delay_ms(uint32_t ms)
{
	timer_t tim;
	Timer_set(&tim, ms);
	// Ждём, пока таймер не истечёт
	while (!Timer_isExpired(&tim)) ;
	// Цикл завершится, когда Timer_isExpired вернёт 1
}