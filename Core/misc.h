/**
 * @file misc.h
 * @brief Заголовочный файл с вспомогательными функциями и определениями.
 *
 * Содержит макросы для работы с АЦП, функции для поиска медианы,
 * преобразования чисел в строки и таймерные функции.
 *
 * Логика работы:
 * - GET_ADC_K / GET_mV: Макросы для вычисления напряжения (в мВ) из
 *   значения АЦП с использованием коэффициента, рассчитанного на основе
 *   опорного напряжения и значения АЦП для этого напряжения.
 * - GetMedian_16: Сортирует массив и возвращает медиану.
 * - Int_to_str: Преобразует 32-битное целое число в строку (с выравниванием вправо).
 * - Timer_*: Функции для работы с программными таймерами, основанными на
 *   глобальной переменной `timer_ms`.
 */

#ifndef __MISC_H__
#define __MISC_H__

#include <stddef.h>
#include <stdint.h>

// ================== ОПРЕДЕЛЕНИЯ (DEFINES) ==================

/**
 * @brief Вычисление коэффициента для преобразования значения АЦП в мВ.
 *
 * Этот макрос рассчитывает коэффициент, используемый для преобразования
 * значения АЦП в милливольты. Коэффициент рассчитывается как:
 * (Vref_mV << 19) / ADCref.
 * Предполагается, что Vref_mV <= 11 бит и ADCref >= 10 бит.
 *
 * @param Vref_mV Опорное напряжение в мВ.
 * @param ADCref Значение АЦП, соответствующее Vref_mV.
 * @return Коэффициент для использования в GET_mV.
 */
#define GET_ADC_K(Vref_mV, ADCref) ( ((uint32_t)(Vref_mV)<<19) / ((uint32_t)(ADCref)) )

/**
 * @brief Преобразование значения АЦП в милливольты.
 *
 * Использует предварительно рассчитанный коэффициент (GET_ADC_K) для
 * преобразования значения АЦП в напряжение в милливольтах.
 * Формула: (ADC_val * ADC_K) >> 19.
 *
 * @param ADC_val Значение АЦП.
 * @param ADC_K Коэффициент, рассчитанный с помощью GET_ADC_K.
 * @return Напряжение в мВ.
 */
#define GET_mV(ADC_val, ADC_K) ( ((uint32_t)(ADC_val) * (uint32_t)(ADC_K)) >> 19 )

// ================== ФУНКЦИИ (FUNCTIONS) ==================

/**
 * @brief Поиск медианы в массиве 16-битных значений.
 *
 * Сортирует переданный массив методом вставки и возвращает значение
 * элемента, находящегося в середине отсортированного массива.
 * @warning Массив `arr` изменяется в процессе сортировки.
 *
 * @param[in,out] arr Указатель на массив 16-битных значений. Будет отсортирован.
 * @param n Размер массива.
 * @return Медианное значение.
 */
uint16_t GetMedian_16(uint16_t * const arr, int n);

/**
 * @brief Преобразование 32-битного целого числа в строку.
 *
 * Преобразует целое число `var` в строку символов, сохраняя её в буфер `str`.
 * Строка выравнивается вправо (незаполненные позиции слева заполняются пробелами).
 * Символ завершающего нуля ('\0') не добавляется автоматически.
 *
 * @param var Целое число для преобразования.
 * @param[out] str Буфер размером 12 байт для результата.
 * @return Количество значимых символов в числе (без ведущих пробелов).
 */
int32_t Int_to_str(int32_t var, char str[12]);

// Таймеры - отслеживание периодов времени

/**
 * @brief Структура для хранения данных программного таймера.
 */
typedef struct
{
	uint32_t timeStamp; ///< Время последней установки или срабатывания таймера.
	uint32_t period;    ///< Период таймера в миллисекундах.
} timer_t;

/**
 * @brief Установка программного таймера.
 *
 * Инициализирует таймер, устанавливая его период и отметку времени
 * на текущее значение глобальной переменной `timer_ms`.
 *
 * @param[out] tim Указатель на структуру таймера.
 * @param period Период таймера в миллисекундах.
 */
void Timer_set(timer_t *tim, uint32_t period);

/**
 * @brief Проверка истечения программного таймера.
 *
 * Проверяет, истёк ли период с момента последней установки/срабатывания таймера.
 * Если таймер истёк, автоматически обновляет `timeStamp` на `period` вперёд
 * и возвращает 1.
 *
 * @param[in,out] tim Указатель на структуру таймера.
 * @return 1, если таймер истёк, 0 - если нет.
 */
uint8_t Timer_isExpired(timer_t *tim);

/**
 * @brief Блокирующая задержка в миллисекундах.
 *
 * Создаёт программный таймер и ждёт, пока он не истечёт.
 * Использует `Timer_set` и `Timer_isExpired`.
 *
 * @param ms Количество миллисекунд для задержки.
 */
void Timer_delay_ms(uint32_t ms);

#endif //__MISC_H__